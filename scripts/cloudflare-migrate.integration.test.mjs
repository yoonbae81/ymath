import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp,mkdir,writeFile,readFile,rm } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { getPlatformProxy } from 'wrangler';
import sharp from 'sharp';
import { manifestSnapshot,compareManifests,importLocalSnapshot,exportLocalSnapshot,initializeLocalDatabase } from './cloudflare-migrate.mjs';

test('real local Wrangler D1/R2 preserves every source SHA and rollback includes post-cutover writes', async () => {
 const root=await mkdtemp(join(tmpdir(),'ymath-migrate-e2e-')); let proxy;
 try {
  const source=join(root,'source'),id='20261017-080000-abcd',reportId='20261017-080001-rep-abcd';
  await mkdir(join(source,'items',id),{recursive:true}); await mkdir(join(source,'reports'),{recursive:true});
  const meta={provider:'codex',model:'TEST-ONLY',prompt_version:'fixture',analyzed_at:'2026-10-17T08:00:00Z'};
  const record={schema_version:1,id,status:'done',created_at:'2026-10-17T08:00:00Z',image:'image.jpg',workbook:{id:'fixture',name:'Fixture'},analysis:{asks:'TEST ONLY'},meta,flags:{ocr_missing:true,taxonomy_mismatch:[],guardrail:[]},feedback:[{choice:'accurate',analyzed_at:meta.analyzed_at}],favorite:false};
  await writeFile(join(source,'items',id,'record.json'),JSON.stringify(record,null,2));
  await writeFile(join(source,'items',id,'image.jpg'),await sharp({create:{width:24,height:32,channels:3,background:'#aaa'}}).jpeg().toBuffer());
  await writeFile(join(source,'items',id,'ocr.md'),'TEST-ONLY fixture OCR');
  await writeFile(join(source,'items',id,'analysis-codex.json'),JSON.stringify({analysis:record.analysis,meta,flags:record.flags}));
  await writeFile(join(source,'reports',`${reportId}.json`),JSON.stringify({schema_version:1,id:reportId,status:'done',created_at:record.created_at,item_ids:[id],markdown:'TEST ONLY report',meta:null}));
  const config=join(root,'wrangler.json');
  await writeFile(config,JSON.stringify({name:'ymath-migration-fixture',compatibility_date:'2026-10-17',d1_databases:[{binding:'DB',database_name:'migration-fixture',database_id:'local-migration-fixture'}],r2_buckets:[{binding:'OBJECTS',bucket_name:'migration-fixture-private'}]}));
  proxy=await getPlatformProxy({configPath:config,persist:{path:join(root,'state')},remoteBindings:false,envFiles:[]});
  const env=proxy.env;
  await initializeLocalDatabase(env);
  const before=await manifestSnapshot(source);
  const imported=await importLocalSnapshot(env,source,join(root,'backup'));
  const leaseIndex=await env.DB.prepare("SELECT name FROM sqlite_master WHERE type='index' AND name='jobs_provider_lease'").first();
  assert.ok(leaseIndex,'migration helper must apply every current schema migration');
  assert.deepEqual(imported.itemIds,before.itemIds);
  const importedOcr=await env.DB.prepare('SELECT ocr_key FROM entities WHERE id=?').bind(id).first();
  assert.ok(importedOcr.ocr_key,'source OCR must be linked from the imported D1 entity');
  const exported=join(root,'export-before'); await exportLocalSnapshot(env,exported);
  assert.deepEqual(compareManifests(before,await manifestSnapshot(exported)),[]);
  await env.DB.prepare('UPDATE entities SET favorite=1,viewed_at=? WHERE id=?').bind('2026-10-17T09:00:00Z',id).run();
  await env.DB.prepare('UPDATE feedback SET payload_json=? WHERE entity_id=?').bind(JSON.stringify({...record.feedback[0],choice:'learned'}),id).run();
  const currentOcr=Buffer.from('TEST-ONLY updated current OCR');
  await env.OBJECTS.put(importedOcr.ocr_key,currentOcr);
  await env.DB.prepare("UPDATE entities SET report_json=json_set(report_json,'$.markdown','post-cutover report') WHERE id=?").bind(reportId).run();
  const newId='20261017-090000-efgh',newImageKey=`postcutover/${newId}/image.jpg`;
  const imageBytes=await readFile(join(source,'items',id,'image.jpg'));
  await env.OBJECTS.put(newImageKey,imageBytes);
  const newRecord={...record,id:newId,feedback:[]};
  await env.DB.prepare("INSERT INTO entities(id,kind,created_at,status,record_json,image_key,updated_at) VALUES(?,'item',?,'done',?,?,?)").bind(newId,record.created_at,JSON.stringify(newRecord),newImageKey,record.created_at).run();
  const rollback=join(root,'rollback'); await exportLocalSnapshot(env,rollback);
  const restored=JSON.parse(await readFile(join(rollback,'items',id,'record.json'),'utf8'));
  assert.equal(restored.favorite,true); assert.equal(restored.viewed_at,'2026-10-17T09:00:00Z'); assert.equal(restored.feedback[0].choice,'learned');
  assert.equal(await readFile(join(rollback,'items',id,'ocr.md'),'utf8'),currentOcr.toString());
  assert.equal(JSON.parse(await readFile(join(rollback,'reports',`${reportId}.json`),'utf8')).markdown,'post-cutover report');
  assert.equal(JSON.parse(await readFile(join(rollback,'items',newId,'record.json'),'utf8')).id,newId);
  assert.equal(Buffer.compare(await readFile(join(rollback,'items',newId,'image.jpg')),imageBytes),0);
  assert.deepEqual((await manifestSnapshot(rollback)).itemIds,[id,newId]);
  assert.deepEqual(compareManifests(before,await manifestSnapshot(join(root,'backup'))),[]);
  await env.DB.prepare("UPDATE entities SET deleted_at='2026-10-17T10:00:00Z'").run();
  const empty=await exportLocalSnapshot(env,join(root,'rollback-deleted'));
  assert.deepEqual(empty.itemIds,[]); assert.deepEqual(empty.reportIds,[]); assert.deepEqual(empty.files,[]);
  console.log(JSON.stringify({fixtureRoot:root,items:before.itemIds.length,reports:before.reportIds.length,shaVerified:before.files.length,postCutoverRollback:true,deletionsPreserved:true,bindingsMode:'local-only'}));
 } finally { if(proxy) await proxy.dispose(); /* retain fixture evidence for independent inspection */ }
});
